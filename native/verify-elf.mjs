import { execFileSync } from 'node:child_process';
import assert from 'node:assert/strict';
import {readFileSync} from 'node:fs';
const args=process.argv.slice(2),arg=name=>args.includes(name)?args[args.indexOf(name)+1]:undefined;
const readelf=arg('--readelf'),file=arg('--library');
const abi=arg('--abi')||'arm64-v8a';
assert(readelf&&file,'Usage: verify-elf.mjs --readelf PATH --library PATH');
assert(['arm64-v8a','x86_64'].includes(abi),'Unsupported ABI');
const run=(...flags)=>execFileSync(readelf,[...flags,file],{encoding:'utf8'});
const header=readFileSync(file).subarray(0,64);
assert.equal(header.subarray(0,4).toString('hex'),'7f454c46','ELF magic required');
assert.equal(header[4],2,'ELF64 required');assert.equal(header[5],1,'Little-endian ELF required');
assert.equal(header.readUInt16LE(18),abi==='arm64-v8a'?183:62,`ELF machine must match ${abi}`);
const dyn=run('--dyn-syms','--wide');
const symbols=dyn.split('\n').map(line=>line.trim().split(/\s+/)).filter(p=>p.length>=8&&/^\d+:$/.test(p[0]));
const exported=symbols.filter(p=>['GLOBAL','WEAK'].includes(p[4])&&p[6]!=='UND'&&p[5]==='DEFAULT').map(p=>p[7].split('@')[0]);
assert(exported.includes('JNI_OnLoad'),'JNI_OnLoad must be exported');
assert(exported.every(n=>['JNI_OnLoad','FAMILYGRAM_1'].includes(n)),`Unexpected exported symbols: ${exported.join(', ')}`);
const undefinedNames=symbols.filter(p=>p[6]==='UND').map(p=>p[7].split('@')[0]);
for(const forbidden of ['socket','connect','gethostbyname','getaddrinfo']) assert(!undefinedNames.includes(forbidden),`Native direct-network import survived: ${forbidden}`);
const dynamic=run('-d');
assert(!dynamic.includes('libtmessages'),'Override must not link to original tgnet symbols');
assert(!dynamic.includes('libc++_shared'),'Use isolated statically linked libc++');
assert.match(dynamic,/BIND_NOW|NOW/,'Immediate symbol binding required');
const segments=run('-l','--wide');
assert.match(segments,/GNU_RELRO/,'RELRO required');
const loadSegments=segments.split('\n').map(line=>line.trim().split(/\s+/)).filter(parts=>parts[0]==='LOAD');
assert(loadSegments.length>0,'ELF load segments required');
assert(loadSegments.every(parts=>Number.parseInt(parts.at(-1),16)>=0x4000),'Every LOAD segment must support 16 KiB page alignment');
console.log(`ELF verified: ${abi}, private symbols, no direct TCP/DNS imports, no original-library dependency.`);
